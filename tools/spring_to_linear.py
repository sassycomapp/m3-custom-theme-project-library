"""Turn the M3 spring tokens into CSS easings.

M3 Expressive motion is spring-based. A browser cannot run a spring in CSS
directly, but it can follow any curve given as points with the CSS linear()
easing. This script reads every spring token (stiffness and damping ratio,
mass 1) from theme/assets/m3x/tokens.css, solves the spring's motion from 0 to
1, and writes for each spring:

    --m3x-motion-spring-<scheme>-<speed>-<kind>-easing    linear(...) points
    --m3x-motion-spring-<scheme>-<speed>-<kind>-duration  the settling time

The settling time is when the spring stays within 0.1 % of its target. The
output replaces the block between the BEGIN and END markers in tokens.css, so
the file is never edited by hand there.

Usage, from the project library root:

    python tools/spring_to_linear.py ../m3-custom-theme
"""
import math
import re
import sys
from pathlib import Path

POINTS = 32            # Points per curve, spread evenly over the duration.
SETTLE = 0.001         # The spring has settled within 0.1 % of its target.
BEGIN = "  /* BEGIN generated by tools/spring_to_linear.py: do not edit by hand */"
END = "  /* END generated by tools/spring_to_linear.py */"


def position(t, stiffness, damping):
    """Where a spring released at 0, heading for 1, is after t seconds."""
    w0 = math.sqrt(stiffness)
    if damping < 1:
        wd = w0 * math.sqrt(1 - damping * damping)
        decay = math.exp(-damping * w0 * t)
        return 1 - decay * (math.cos(wd * t) + damping * w0 / wd * math.sin(wd * t))
    if damping == 1:
        return 1 - math.exp(-w0 * t) * (1 + w0 * t)
    root = math.sqrt(damping * damping - 1)
    r1, r2 = -w0 * (damping - root), -w0 * (damping + root)
    return 1 - (r2 * math.exp(r1 * t) - r1 * math.exp(r2 * t)) / (r2 - r1)


def settling_time(stiffness, damping):
    """The first time after which the spring never leaves 1 +/- SETTLE."""
    step, t, last_outside = 0.001, 0.0, 0.0
    while t < 5:
        if abs(1 - position(t, stiffness, damping)) > SETTLE:
            last_outside = t
        t += step
    return last_outside + step


def easing(stiffness, damping):
    duration = settling_time(stiffness, damping)
    values = [position(duration * i / POINTS, stiffness, damping)
              for i in range(POINTS + 1)]
    values[0], values[-1] = 0.0, 1.0
    points = ", ".join(f"{v:.4f}".rstrip("0").rstrip(".") or "0" for v in values)
    return f"linear({points})", round(duration * 1000)


def main(app_root):
    tokens = Path(app_root) / "theme" / "assets" / "m3x" / "tokens.css"
    text = tokens.read_text(encoding="utf-8")
    pattern = re.compile(
        r"--m3x-motion-spring-([a-z]+)-([a-z]+)-([a-z]+)-stiffness:\s*([\d.]+);"
        r"\s*--m3x-motion-spring-\1-\2-\3-damping:\s*([\d.]+);")
    lines = [BEGIN]
    for scheme, speed, kind, stiffness, damping in pattern.findall(text):
        curve, ms = easing(float(stiffness), float(damping))
        name = f"--m3x-motion-spring-{scheme}-{speed}-{kind}"
        lines.append(f"  {name}-easing: {curve};")
        lines.append(f"  {name}-duration: {ms}ms;")
    lines.append(END)
    block = "\n".join(lines)
    if BEGIN in text:
        start = text.index(BEGIN)
        end = text.index(END) + len(END)
        text = text[:start] + block + text[end:]
    else:
        raise SystemExit(f"Add the BEGIN and END markers to {tokens} first.")
    tokens.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {len(lines) - 2} values to {tokens}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "../m3-custom-theme")
